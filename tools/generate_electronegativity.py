#!/usr/bin/env python3
"""Writes Sources/ShellPhaseLibrary/PaulingElectronegativity.swift from pymatgen's periodic table ("X" of
pymatgen/core/periodic_table.json.gz, read through `Element.X`). Elements whose X is NaN are left out of the table: pymatgen's
`Composition.formula` sorts them last (`_symbol_sort_order`: NaN becomes inf, ties by symbol), as the Swift side does.

    python3 -m venv v && v/bin/pip install pymatgen-core && v/bin/python tools/generate_electronegativity.py
"""
import importlib.metadata
import math
import pathlib

from pymatgen.core import Element

version = importlib.metadata.version("pymatgen-core")
entries = [(e.Z, e.symbol, e.X) for e in Element if not math.isnan(e.X)]
entries.sort()
rows = []
line = "       "
for _, symbol, x in entries:
    item = f' "{symbol}": {x!r},'
    if len(line) + len(item) > 128:
        rows.append(line)
        line = "       "
    line += item
rows.append(line)

out = f'''//
//  PaulingElectronegativity.swift
//  GENERATED by tools/generate_electronegativity.py from pymatgen-core {version} (pymatgen/core/periodic_table.json.gz, "X",
//  read as `Element.X`). Do not edit; run the script.
//  Role: the order of a formula's elements, as pymatgen's `Composition.formula` and `reduced_formula` write it: by increasing
//        electronegativity, so SiO2, Fe2O3, ZnO, GaN. An element whose X is NaN in pymatgen is not in the table and sorts last,
//        as pymatgen's `_symbol_sort_order` does (NaN as infinity). Ties sort by symbol.
//

enum PaulingElectronegativity {{
    static func value(of symbol: String) -> Double {{ table[symbol] ?? .infinity }}

    /// The symbols in a formula's order.
    static func ordered(_ symbols: [String]) -> [String] {{
        symbols.sorted {{ a, b in
            let x = value(of: a), y = value(of: b)
            return x == y ? a < b : x < y
        }}
    }}

    private static let table: [String: Double] = [
{chr(10).join(rows)}
    ]
}}
'''
target = pathlib.Path(__file__).resolve().parent.parent / "Sources/ShellPhaseLibrary/PaulingElectronegativity.swift"
target.write_text(out)
print(f"{len(entries)} elements -> {target}")
